// ==================== TIPOS DA BARRA DE COMANDOS ====================
// Direcoes/acoes possiveis em um item da barra de comandos do rodape.
enum CmdDir
{
  CMD_OK,
  CMD_UP,
  CMD_DOWN,
  CMD_LEFT,
  CMD_RIGHT
};

// Um item da barra: a tecla (seta ou OK) e o rotulo da acao.
struct CmdEntry
{
  uint8_t dir;
  const char *label;
};

// ==================== LEITURA DE SENSOR (multi-protocolo) ====================
// Definido aqui (e nao no .ino) para evitar o erro de "not declared" causado
// pelos prototipos automaticos do Arduino quando uma funcao recebe este tipo.
struct SensorReading
{
  const char *proto; // nome do protocolo decodificado (ex.: "Nexus", "Acurite")
  int id;
  int channel;
  float tempC;
  int humidity; // % de umidade (-1 se o protocolo nao tiver)
  int battery;  // 1 = ok, 0 = fraca, -1 = desconhecido
};

// Assinatura de um parser: recebe os bits de um quadro e tenta preencher 'out'.
typedef bool (*SensorParser)(const uint8_t *bits, int nbits, SensorReading *out);

